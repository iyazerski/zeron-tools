// Writes file-icons.js: the colour file-type badges Zeron shows on its tool
// rows, for the names and extensions agents touch most. They come from
// rune-theme-opencode's catalog (the one the Companion draws), so both look
// the same. Run: bun make_file_icons.ts <rune checkout>/themes/opencode/src/file_icons/catalog.rs

const NAMES = [
  "readme.md", "license", "package.json", "dockerfile", "makefile", ".gitignore", "cargo.toml", "cargo.lock",
];
const EXTENSIONS = [
  "rs", "toml", "lock", "md", "mdx", "json", "jsonc", "js", "mjs", "cjs", "ts", "tsx", "jsx", "d.ts", "py", "go",
  "swift", "kt", "java", "rb", "php", "c", "h", "cc", "cpp", "hpp", "cs", "css", "scss", "html", "yaml", "yml",
  "sh", "bash", "zsh", "sql", "txt", "svg", "png", "jpg", "jpeg", "gif", "webp", "xml", "env", "proto", "graphql",
  "vue", "svelte", "lua", "zig", "luau", "csv", "pdf",
];

const src = await Bun.file(process.argv[2]).text();
const icons = new Map<string, { view: number; body: string }>();
for (const m of src.matchAll(/static (\w+): Icon = Icon \{\s*name: "[^"]*",\s*view: ([\d.]+),\s*body: r##"([\s\S]*?)"##,/g)) {
  icons.set(m[1], { view: Number(m[2]), body: m[3] });
}
/** The `key => &ICON` arms of the catalog's `fn <name>`. */
function table(fn: string): Map<string, string> {
  const start = src.indexOf(`fn ${fn}(`);
  const body = src.slice(start, src.indexOf("\n}\n", start));
  return new Map([...body.matchAll(/"([^"]+)" => &(\w+)/g)].map(m => [m[1], m[2]]));
}
const byName = table("by_file_name");
const byExt = table("by_extension");
const pick = (all: Map<string, string>, keys: string[]) =>
  Object.fromEntries(keys.filter(k => all.has(k)).map(k => [k, all.get(k)!]));
const names = pick(byName, NAMES);
const exts = pick(byExt, EXTENSIONS);
const used = new Set([...Object.values(names), ...Object.values(exts), "DOCUMENT"]);
const svgs = Object.fromEntries([...used].sort().map(id => {
  const icon = icons.get(id);
  if (!icon) throw new Error(`no icon ${id}`);
  return [id, [icon.view, icon.body]];
}));

const out = `// Generated by make_file_icons.ts from rune-theme-opencode's file icons. Do not edit.
"use strict";
const FILE_ICONS = {
  svgs: ${JSON.stringify(svgs)},
  names: ${JSON.stringify(names)},
  exts: ${JSON.stringify(exts)},
};
`;
await Bun.write(new URL("file-icons.js", import.meta.url), out);
console.log(`${used.size} icons, ${out.length} bytes`);
